#!/bin/bash

echo "=========================================="
echo "  分割面板和可视化功能演示"
echo "=========================================="
echo ""
echo "编译并运行程序..."
echo ""

cargo run &

sleep 3

cat << 'EOF'

✅ 程序已启动!

📋 操作步骤:

1. 【加载数据】
   - 拖放一个 SQLite 数据库文件到窗口
   - 或使用 NSYS 导出的 .sqlite 文件

2. 【选择表格】
   - 在左侧面板点击任意表名
   - 右侧会自动加载表格数据和可视化

3. 【面板控制】
   - 点击 "✓ 表格" 切换表格面板
   - 点击 "✓ 可视化" 切换可视化面板
   - 两个面板可以独立开关

4. 【调整布局】
   - 拖动中间的分割线调整表格/可视化的高度比例
   - 点击 "🔄 重置视图" 恢复 50:50 比例

5. 【可视化交互】
   - 🖱️ 滚轮: 缩放视图 (10% - 1000%)
   - 🖱️ 拖动: 平移视图
   - 🔘 重置缩放: 恢复初始状态

6. 【表格分页】
   - 点击 "⏮ 上一页" / "下一页 ⏭" 浏览数据
   - 每页默认显示 100 行

📊 可视化类型:

• 散点图: 当表中有 ≥2 个数值列时
  → 显示 X-Y 坐标关系

• 柱状图: 当表中有 1 个数值列时
  → 显示数值大小分布

• 数据摘要: 当表中没有数值列时
  → 显示基本统计信息

💡 提示:

- 使用右上角的 "⚙ 日志设置" 调整日志等级
- 底部状态栏显示当前日志等级
- 所有操作都有详细的日志记录

🔍 测试建议:

1. 尝试不同的表 → 观察自动选择的可视化类型
2. 放大缩小 → 查看可视化细节
3. 切换面板 → 体验不同的显示模式
4. 调整分割线 → 找到最适合的布局

按 Ctrl+C 停止程序

EOF

# 等待用户
wait
